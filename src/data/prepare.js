/*
 * Prepare Data — runs inside the GUI process.
 *
 * Replaces run-server.bat + Config/convert.js + json-server for the GUI:
 *   TestData/**\/*.xlsx  ->  JsonData/<Excel>/<Sheet>.json   (for viewing)
 *                        ->  Scripts/<Excel>/<Sheet>.js      (data embedded)
 *
 * The generated .js files contain the sheet rows directly, so Maestro's
 * runScript no longer needs an HTTP server on port 8080. Output paths are
 * the same as before, so existing flows (runScript: "../Scripts/X/Y.js")
 * keep working without any change.
 */

const fs   = require("fs");
const path = require("path");

const P = require("../core/paths");     // project folders (the open project can change)
const MARKER      = "// Auto-generated by Maestro Flow Runner";

/*
 * Excel reader (2.0.1). `xlsx` (SheetJS) is no longer an npm dependency: it is only
 * published as a file on cdn.sheetjs.com, and newer npm versions / company npm policies
 * refuse such "remote" packages (EALLOWREMOTE), so the whole install failed on work PCs.
 *   - exceljs (normal npm package, already required by the Excel editor) is the reader now
 *   - if an older install still has `xlsx` in node_modules, it is used as before, so the
 *     generated data stays exactly the same on PCs that already work
 * Cells are turned into the text Excel shows (leading zeros, dates, percentages), the
 * same rule as before: Maestro types text anyway.
 */
let XLSX = null, ExcelJS = null;
try { XLSX = require("xlsx"); } catch (_) {}
try { ExcelJS = require("exceljs"); } catch (_) {}

const safe = s => String(s).trim().replace(/[^a-zA-Z0-9_-]/g, "_");

function findExcel(dir, out) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory() && !e.name.startsWith(".")) findExcel(full, out);
    else if (/\.xlsx?$/i.test(e.name) && !e.name.startsWith("~$")) out.push(full);
  }
  return out;
}

// Env variable that selects the row for one sheet, e.g. ROW_TripTestData_WithinCity.
// Each sheet has its own variable, so a flow that uses two Excel files
// (e.g. login + trip data) can run trip row 7 while login stays on row 1.
function rowVar(excelBase, sheetSafe) {
  return "ROW_" + safe(excelBase) + "_" + safe(sheetSafe);
}

// Row 1 = column names. Columns with a blank name and rows with no values
// are ignored, so leftover formatting in Excel never becomes "data".
function rowsFromAoa(aoa) {
  if (!aoa.length) return [];
  const heads = aoa[0].map(h => String(h == null ? "" : h).trim());
  const rows = [];
  for (const line of aoa.slice(1)) {
    const obj = {};
    let any = false;
    heads.forEach((h, i) => {
      if (!h) return;
      const v = line[i] == null ? "" : String(line[i]);
      obj[h] = v;                          // empty cells stay "" so ${output.col} is never undefined
      if (v.trim() !== "") any = true;
    });
    if (any) rows.push(obj);
  }
  return rows;
}

/* SheetJS (older installs) */
function sheetRows(ws) {
  // raw:false -> text exactly as Excel shows it (keeps leading zeros, formats dates)
  return rowsFromAoa(XLSX.utils.sheet_to_json(ws, { header: 1, defval: "", raw: false, blankrows: false }));
}

/* ---------- ExcelJS: a cell as the text Excel shows ---------- */
const MONTHS = ["January","February","March","April","May","June","July","August","September","October","November","December"];
const DAYS   = ["Sunday","Monday","Tuesday","Wednesday","Thursday","Friday","Saturday"];
const pad = (n, w) => String(n).padStart(w, "0");

// Excel's built-in date formats (numFmtId 14-22) arrive without a format string
const DEFAULT_DATE_FMT = "m/d/yy";

function fmtDate(d, fmt) {
  // ExcelJS gives dates as UTC moments of the wall-clock time in the sheet
  const Y = d.getUTCFullYear(), M = d.getUTCMonth(), D = d.getUTCDate(), wd = d.getUTCDay();
  const h = d.getUTCHours(), mi = d.getUTCMinutes(), sec = d.getUTCSeconds();
  // Built-in format 14 (the short date): ExcelJS names it "mm-dd-yy", Excel / SheetJS show 1/5/24
  if (!fmt || fmt === "mm-dd-yy") fmt = DEFAULT_DATE_FMT;
  let f = String(fmt).replace(/\[[^\]]*\]/g, "").replace(/\\(.)/g, "$1").replace(/"([^"]*)"/g, "$1");
  const ampm = /AM\/PM|A\/P/i.test(f);
  const tokens = f.match(/yyyy|yy|mmmmm|mmmm|mmm|mm|m|dddd|ddd|dd|d|hh|h|ss|s|AM\/PM|A\/P|./gi) || [];
  let out = "", lastWasHour = false;
  for (let i = 0; i < tokens.length; i++) {
    const t = tokens[i], tl = t.toLowerCase();
    // "m" right after an hour, or right before seconds, means minutes
    const nextReal = tokens.slice(i + 1).find(x => /[a-z]/i.test(x)) || "";
    const minutes = (tl === "m" || tl === "mm") && (lastWasHour || /^s/i.test(nextReal));
    if (tl === "yyyy") out += Y;
    else if (tl === "yy") out += pad(Y % 100, 2);
    else if (minutes) out += tl === "mm" ? pad(mi, 2) : mi;
    else if (tl === "mmmmm") out += MONTHS[M][0];
    else if (tl === "mmmm") out += MONTHS[M];
    else if (tl === "mmm") out += MONTHS[M].slice(0, 3);
    else if (tl === "mm") out += pad(M + 1, 2);
    else if (tl === "m") out += M + 1;
    else if (tl === "dddd") out += DAYS[wd];
    else if (tl === "ddd") out += DAYS[wd].slice(0, 3);
    else if (tl === "dd") out += pad(D, 2);
    else if (tl === "d") out += D;
    else if (tl === "hh" || tl === "h") { const hv = ampm ? (h % 12 || 12) : h; out += tl === "hh" ? pad(hv, 2) : hv; }
    else if (tl === "ss") out += pad(sec, 2);
    else if (tl === "s") out += sec;
    else if (tl === "am/pm") out += h < 12 ? "AM" : "PM";
    else if (tl === "a/p") out += h < 12 ? "A" : "P";
    else out += t;
    if (/[a-z]/i.test(t)) lastWasHour = tl === "h" || tl === "hh";
  }
  return out;
}

function fmtNumber(v, fmt) {
  const f0 = String(fmt || "General");
  if (!fmt || /^general$/i.test(f0)) {
    // Excel "General": up to 11 significant digits, no float noise (0.1+0.2 -> 0.3)
    return Number.isInteger(v) ? String(v) : String(+v.toPrecision(11));
  }
  if (f0 === "@") return String(v);
  const f = f0.split(";")[v < 0 ? 1 : 0] || f0.split(";")[0];
  const neg = v < 0 && f0.split(";").length < 2;
  const core = f.replace(/"[^"]*"|\\.|\[[^\]]*\]|_.|\*./g, "");
  const pct = core.includes("%");
  let n = Math.abs(v) * (pct ? 100 : 1);
  const m = core.match(/[0#?,]+(?:\.([0#?]+))?/);
  if (!m) return String(v);
  const decimals = m[1] ? m[1].replace(/[^0]/g, "").length : 0;
  const maxDec   = m[1] ? m[1].length : 0;
  const intPat = m[0].split(".")[0];
  const minInt = (intPat.replace(/,/g, "").match(/0/g) || []).length;
  let txt = n.toFixed(maxDec);
  if (maxDec > decimals) txt = txt.replace(new RegExp("0{0," + (maxDec - decimals) + "}$"), "").replace(/\.$/, "");
  let [ip, dp] = txt.split(".");
  if (ip === "0" && minInt === 0) ip = "";
  ip = ip.padStart(minInt, "0");
  if (intPat.includes(",")) ip = ip.replace(/\B(?=(\d{3})+(?!\d))/g, ",");
  const body = ip + (dp !== undefined ? "." + dp : "");
  // keep the literal text around the number ("kg", "$", "%")
  const lit = s => s.replace(/"([^"]*)"/g, "$1").replace(/\\(.)/g, "$1").replace(/\[[^\]]*\]|_.|\*./g, "");
  const at = f.indexOf(m[0]);
  return (neg ? "-" : "") + lit(f.slice(0, at)) + body + lit(f.slice(at + m[0].length));
}

function cellText(cell) {
  let v = cell.value;
  if (v == null) return "";
  if (typeof v === "object" && !(v instanceof Date)) {
    if (v.richText) return v.richText.map(r => r.text).join("");
    if ("result" in v || "formula" in v || "sharedFormula" in v) v = v.result;   // formula: its last result
    else if ("text" in v) return String(v.text);                                  // hyperlink
    else if ("error" in v) return String(v.error);
    if (v == null) return "";
    if (v && typeof v === "object" && v.error) return String(v.error);
  }
  const fmt = cell.numFmt;
  if (v instanceof Date) return isNaN(v) ? "" : fmtDate(v, fmt);
  if (typeof v === "boolean") return v ? "TRUE" : "FALSE";
  if (typeof v === "number") {
    // a number with a date format that ExcelJS did not turn into a Date
    if (fmt && /[dy]|h{1,2}:|m{3,}/i.test(String(fmt).replace(/"[^"]*"|\[[^\]]*\]/g, "")) && !/[0#]/.test(fmt))
      return fmtDate(new Date(Math.round((v - 25569) * 86400000)), fmt);
    return fmtNumber(v, fmt);
  }
  return String(v);
}

function worksheetAoa(ws) {
  const aoa = [];
  const cols = ws.columnCount || 0;
  ws.eachRow({ includeEmpty: false }, row => {
    const line = [];
    for (let c = 1; c <= cols; c++) line.push(cellText(row.getCell(c)));
    if (line.some(x => x !== "")) aoa.push(line);
  });
  return aoa;
}

/** [{ name, rows }] for every sheet of one Excel file. */
async function readWorkbook(file) {
  if (XLSX) {
    const wb = XLSX.readFile(file);
    return wb.SheetNames.map(name => ({ name, rows: sheetRows(wb.Sheets[name]) }));
  }
  if (/\.xls$/i.test(file)) throw new Error("old .xls format: open it in Excel and save it as .xlsx");
  const wb = new ExcelJS.Workbook();
  await wb.xlsx.readFile(file);
  const out = [];
  wb.eachSheet(ws => { out.push({ name: ws.name, rows: rowsFromAoa(worksheetAoa(ws)) }); });
  return out;
}

function scriptSource(excelRel, sheet, rows, varName) {
  // ES5 only: Maestro's JS engine is not a full modern Node runtime.
  // Row choice: this sheet's own variable, else ROW_NO (CLI use), else row 1.
  return [
    MARKER + " from " + excelRel + " [" + sheet + "]. Do not edit.",
    "var data = " + JSON.stringify(rows, null, 2) + ";",
    "",
    "var ROW_PICK = typeof " + varName + " != 'undefined' ? " + varName +
      " : (typeof ROW_NO != 'undefined' ? ROW_NO : 1);",
    "var index = parseInt(ROW_PICK, 10) - 1;",
    "var row = data[index];",
    "",
    "if (!row) {",
    "  throw new Error('Row ' + (index + 1) + ' not found in " + sheet.replace(/'/g, "") +
      " (' + data.length + ' rows)');",
    "}",
    "Object.keys(row).forEach(function (key) {",
    "  output[key] = row[key];",
    "});",
    ""
  ].join("\n");
}

// Delete generated files we no longer produce (renamed/removed sheets).
// Only touches files that carry our marker, never hand-written scripts.
function removeStale(dir, keep, log) {
  if (!fs.existsSync(dir)) return;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) { removeStale(full, keep, log); continue; }
    if (keep.has(full) || !/\.js$/i.test(e.name)) continue;
    const head = fs.readFileSync(full, "utf8").slice(0, 200);
    if (head.startsWith(MARKER) || head.startsWith("// Auto-generated setup file")) {
      fs.unlinkSync(full);
      log("  [removed stale] " + path.relative(P.root, full) + "\n");
    }
  }
}

/**
 * @param {(text:string)=>void} log  streamed to the GUI console
 * @returns {Promise<{ ok:boolean, files:number, sheets:number, errors:string[] }>}
 * Async since 2.0.1 (ExcelJS reads files asynchronously). Runs are queued, so two
 * callers never write the same Scripts/ files at the same time.
 */
let queue = Promise.resolve();
function prepareData(log) {
  const p = queue.then(() => prepareNow(log), () => prepareNow(log));
  queue = p.then(() => {}, () => {});
  return p;
}

async function prepareNow(log) {
  log = log || (() => {});
  const errors = [];
  if (!XLSX && !ExcelJS) {
    log("[ERROR] No Excel reader is installed (exceljs). Close Understudy and open it again to install it.\n");
    return { ok: false, files: 0, sheets: 0, errors: ["exceljs missing"] };
  }

  const files = findExcel(P.testData, []);
  if (!files.length) log("[WARN] No Excel files found in TestData/\n");

  const written = new Set();
  let sheetCount = 0;

  for (const file of files) {
    const rel      = path.relative(P.root, file).split(path.sep).join("/");
    const baseName = path.basename(file, path.extname(file));
    log("[FILE] " + rel + "\n");
    let sheets;
    try { sheets = await readWorkbook(file); }
    catch (e) {
      const msg = rel + ": " + (e.code === "EBUSY" ? "file is locked (close it in Excel)" : e.message);
      errors.push(msg); log("  [ERROR] " + msg + "\n");
      continue;
    }

    for (const { name: sheet, rows } of sheets) {
      const name = safe(sheet);
      const jsonOut = path.join(P.jsonData, baseName, name + ".json");
      const jsOut   = path.join(P.scripts, baseName, name + ".js");
      fs.mkdirSync(path.dirname(jsonOut), { recursive: true });
      fs.mkdirSync(path.dirname(jsOut),   { recursive: true });
      fs.writeFileSync(jsonOut, JSON.stringify(rows, null, 2));
      fs.writeFileSync(jsOut, scriptSource(rel, sheet, rows, rowVar(baseName, name)));
      written.add(jsOut);
      sheetCount++;
      log("  [OK] " + sheet + " -> Scripts/" + baseName + "/" + name + ".js (" + rows.length + " rows)\n");
    }
  }

  // If a file could not be read (e.g. open in Excel), keep old scripts
  // rather than deleting them as stale.
  if (!errors.length) removeStale(P.scripts, written, log);
  log("[DONE] " + files.length + " file(s), " + sheetCount + " sheet(s)" +
      (errors.length ? ", " + errors.length + " error(s)" : "") + "\n");
  return { ok: errors.length === 0, files: files.length, sheets: sheetCount, errors };
}

